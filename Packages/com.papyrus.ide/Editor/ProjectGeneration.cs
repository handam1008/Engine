    /// <summary>
    /// Writes SDK-style .csproj files and a .sln for the Unity project so that the Roslyn
    /// language server (or OmniSharp) can load them with a modern .NET SDK.
    /// </summary>
    internal class ProjectGeneration
    {
        const string k_NewLine = "\r\n";
        const string k_CSharpProjectType = "FAE04EC0-301F-11D3-BF4B-00C04F79EFBC";
        const string k_Marker = "Generated by PAPyrus.";
        static readonly string[] k_SyncExtensions = { ".cs", ".asmdef", ".asmref", ".dll", ".rsp" };
        // Capabilities removed from SDK-style projects, as com.unity.ide.visualstudio's
        // SdkStyleProjectGeneration does (MIT, see "Third Party Notices.md").
        static readonly string[] k_UnsupportedCapabilities =
        {
            "LaunchProfiles", "SharedProjectReferences", "ReferenceManagerSharedProjects", "ReferenceManagerProjects",
            "COMReferences", "ReferenceManagerCOM", "AssemblyReferences", "ReferenceManagerAssemblies",
        };

        readonly Dictionary<string, PackageInfo> m_PackageCache = new Dictionary<string, PackageInfo>();

        public static string ProjectDirectory
        {
            get { return Directory.GetParent(Application.dataPath).FullName; }
        }

        static string ProjectName
        {
            get { return Path.GetFileName(ProjectDirectory); }
        }

        public string SolutionFile
        {
            get
            {
                var name = ProjectName;
                foreach (var c in Path.GetInvalidFileNameChars())
                    name = name.Replace(c, '_');
                return Path.Combine(ProjectDirectory, name + ".sln");
            }
        }

        public bool HasSolutionBeenGenerated()
        {
            return File.Exists(SolutionFile);
        }

        public void SyncIfNeeded(IEnumerable<string> affectedFiles, IEnumerable<string> importedFiles)
        {
            var relevant = affectedFiles.Concat(importedFiles)
                .Any(f => k_SyncExtensions.Contains(Path.GetExtension(f).ToLowerInvariant()));
            if (relevant || !HasSolutionBeenGenerated())
                Sync();
        }

        public void Sync()
        {
            m_PackageCache.Clear();
            var assemblies = CompilationPipeline.GetAssemblies(AssembliesType.Editor)
                .Where(a => a.sourceFiles.Length > 0 && ShouldGenerate(a))
                .OrderBy(a => a.name)
                .ToList();
            var generated = new HashSet<string>(assemblies.Select(a => a.name));

            foreach (var assembly in assemblies)
                WriteIfChanged(ProjectFile(assembly), ProjectText(assembly, generated));

            WriteIfChanged(SolutionFile, SolutionText(assemblies));
            DeleteStaleProjects(generated);
        }

        /// <summary>
        /// Projects we generated earlier for assemblies that are no longer generated (a package switched
        /// off in Preferences, a removed asmdef). Left behind they get loaded twice and never restored.
        /// </summary>
        static void DeleteStaleProjects(HashSet<string> generated)
        {
            try
            {
                foreach (var path in Directory.GetFiles(ProjectDirectory, "*.csproj"))
                {
                    if (generated.Contains(Path.GetFileNameWithoutExtension(path)))
                        continue;
                    string head;
                    using (var reader = new StreamReader(path))
                        head = reader.ReadLine() + reader.ReadLine();
                    if (head != null && head.Contains(k_Marker))
                        File.Delete(path);
                }
            }
            catch (Exception e)
            {
                Debug.LogWarning("[PAPyrus] 오래된 프로젝트 파일 정리 실패: " + e.Message);
            }
        }

        // -------------------------------------------------------------------------------------- filtering

        bool ShouldGenerate(Assembly assembly)
        {
            if (assembly.name == "Papyrus.Ide.Editor")
                return false;

            var first = assembly.sourceFiles[0].Replace('\\', '/');
            if (first.StartsWith("Assets/", StringComparison.Ordinal))
                return true;

            var package = FindPackage(first);
            if (package == null)
                return true;

            switch (package.source)
            {
                case PackageSource.Embedded: return PapyrusSettings.Embedded;
                case PackageSource.Local:
                case PackageSource.LocalTarball: return PapyrusSettings.Local;
                case PackageSource.Registry: return PapyrusSettings.Registry;
                case PackageSource.Git: return PapyrusSettings.Git;
                case PackageSource.BuiltIn: return PapyrusSettings.BuiltIn;
                default: return false;
            }
        }

        PackageInfo FindPackage(string assetPath)
        {
            if (!assetPath.StartsWith("Packages/", StringComparison.Ordinal))
                return null;
            var parts = assetPath.Split('/');
            if (parts.Length < 3)
                return null;
            var key = parts[1];
            PackageInfo info;
            if (!m_PackageCache.TryGetValue(key, out info))
            {
                info = PackageInfo.FindForAssetPath(assetPath);
                m_PackageCache[key] = info;
            }

            return info;
        }

        // Unity gives virtual paths for package files ("Packages/com.foo/X.cs"); map them to disk.
        string ResolvePath(string path)
        {
            var p = path.Replace('\\', '/');
            var package = FindPackage(p);
            if (package != null && !string.IsNullOrEmpty(package.resolvedPath))
            {
                var rest = p.Substring(package.assetPath.Length).TrimStart('/');
                return Path.GetFullPath(Path.Combine(package.resolvedPath, rest));
            }

            return Path.IsPathRooted(path) ? path : Path.GetFullPath(Path.Combine(ProjectDirectory, path));
        }

        string ProjectRelative(string fullPath)
        {
            var root = ProjectDirectory.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar) + Path.DirectorySeparatorChar;
            var normalized = fullPath.Replace(Path.AltDirectorySeparatorChar, Path.DirectorySeparatorChar);
            if (normalized.StartsWith(root, StringComparison.OrdinalIgnoreCase))
                return normalized.Substring(root.Length);
            return normalized;
        }

        // -------------------------------------------------------------------------------------- csproj

        string ProjectFile(Assembly assembly)
        {
            return Path.Combine(ProjectDirectory, assembly.name + ".csproj");
        }

        string ProjectText(Assembly assembly, HashSet<string> generated)
        {
            var rsp = ResponseFileData.Parse(assembly, ProjectDirectory);
            var defines = assembly.defines.Concat(rsp.Defines).Distinct().ToArray();
            var allowUnsafe = assembly.compilerOptions.AllowUnsafeCode || rsp.Unsafe;
            var sb = new StringBuilder();

            sb.Append("<Project>").Append(k_NewLine);
            sb.Append("  <!-- ").Append(k_Marker).Append(" Changes will be overwritten. -->").Append(k_NewLine);
            sb.Append("  <PropertyGroup>").Append(k_NewLine);
            // Separate obj folder per project, set before Sdk.props (MSB3539).
            sb.Append("    <BaseIntermediateOutputPath>").Append(Path.Combine("Temp", "obj", "$(MSBuildProjectName)")).Append("</BaseIntermediateOutputPath>").Append(k_NewLine);
            sb.Append("    <IntermediateOutputPath>$(BaseIntermediateOutputPath)</IntermediateOutputPath>").Append(k_NewLine);
            sb.Append("    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>").Append(k_NewLine);
            sb.Append("    <OutputPath>").Append(Path.Combine("Temp", "bin", "$(MSBuildProjectName)")).Append("</OutputPath>").Append(k_NewLine);
            sb.Append("  </PropertyGroup>").Append(k_NewLine);
            sb.Append("  <Import Project=\"Sdk.props\" Sdk=\"Microsoft.NET.Sdk\" />").Append(k_NewLine);
            sb.Append("  <ItemGroup>").Append(k_NewLine);
            sb.Append("    <ProjectCapability Include=\"Unity\" />").Append(k_NewLine);
            sb.Append("  </ItemGroup>").Append(k_NewLine);

            sb.Append("  <PropertyGroup>").Append(k_NewLine);
            sb.Append("    <TargetFramework>netstandard2.1</TargetFramework>").Append(k_NewLine);
            sb.Append("    <LangVersion>").Append(rsp.LangVersion ?? DefaultLangVersion).Append("</LangVersion>").Append(k_NewLine);
            sb.Append("    <AssemblyName>").Append(Xml(assembly.name)).Append("</AssemblyName>").Append(k_NewLine);
            sb.Append("    <RootNamespace>").Append(Xml(RootNamespace(assembly))).Append("</RootNamespace>").Append(k_NewLine);
            sb.Append("    <OutputType>Library</OutputType>").Append(k_NewLine);
            sb.Append("    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>").Append(k_NewLine);
            sb.Append("    <GenerateTargetFrameworkAttribute>false</GenerateTargetFrameworkAttribute>").Append(k_NewLine);
            sb.Append("    <EnableDefaultItems>false</EnableDefaultItems>").Append(k_NewLine);
            sb.Append("    <NoStandardLibraries>true</NoStandardLibraries>").Append(k_NewLine);
            sb.Append("    <NoStdLib>true</NoStdLib>").Append(k_NewLine);
            sb.Append("    <NoConfig>true</NoConfig>").Append(k_NewLine);
            sb.Append("    <DisableImplicitFrameworkReferences>true</DisableImplicitFrameworkReferences>").Append(k_NewLine);
            sb.Append("    <DisableImplicitNamespaceImports>true</DisableImplicitNamespaceImports>").Append(k_NewLine);
            sb.Append("    <ImplicitUsings>disable</ImplicitUsings>").Append(k_NewLine);
            sb.Append("    <MSBuildWarningsAsMessages>MSB3277</MSBuildWarningsAsMessages>").Append(k_NewLine);
            sb.Append("    <NoWarn>0169;0649;USG0001</NoWarn>").Append(k_NewLine);
            sb.Append("    <DefineConstants>").Append(Xml(string.Join(";", defines))).Append("</DefineConstants>").Append(k_NewLine);
            sb.Append("    <AllowUnsafeBlocks>").Append(allowUnsafe ? "true" : "false").Append("</AllowUnsafeBlocks>").Append(k_NewLine);
            if (!string.IsNullOrEmpty(rsp.Nullable))
                sb.Append("    <Nullable>").Append(rsp.Nullable).Append("</Nullable>").Append(k_NewLine);
            var ruleset = Reflect<string>(assembly.compilerOptions, "RoslynAnalyzerRulesetPath");
            if (!string.IsNullOrEmpty(ruleset))
                sb.Append("    <CodeAnalysisRuleSet>").Append(Escape(Path.GetFullPath(ruleset))).Append("</CodeAnalysisRuleSet>").Append(k_NewLine);
            sb.Append("  </PropertyGroup>").Append(k_NewLine);

            // Sources
            sb.Append("  <ItemGroup>").Append(k_NewLine);
            var dllSources = new List<string>();
            foreach (var file in assembly.sourceFiles)
            {
                if (file.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                {
                    dllSources.Add(ResolvePath(file));
                    continue;
                }

                var full = ResolvePath(file);
                var rel = ProjectRelative(full);
                if (Path.IsPathRooted(rel))
                {
                    sb.Append("    <Compile Include=\"").Append(Escape(rel)).Append("\">").Append(k_NewLine);
                    sb.Append("      <Link>").Append(Escape(file.Replace('/', Path.DirectorySeparatorChar))).Append("</Link>").Append(k_NewLine);
                    sb.Append("    </Compile>").Append(k_NewLine);
                }
                else
                {
                    sb.Append("    <Compile Include=\"").Append(Escape(rel)).Append("\" />").Append(k_NewLine);
                }
            }
            sb.Append("  </ItemGroup>").Append(k_NewLine);

            // Analyzers (Unity's built-in source generators / analyzers, plus any from csc.rsp)
            var analyzers = (Reflect<string[]>(assembly.compilerOptions, "RoslynAnalyzerDllPaths") ?? new string[0]).Concat(rsp.Analyzers)
                .Where(a => !string.IsNullOrEmpty(a)).Select(Path.GetFullPath).Distinct().ToList();
            var unityAnalyzers = Discovery.UnityAnalyzers;
            if (unityAnalyzers != null && !analyzers.Any(a => a.EndsWith("Microsoft.Unity.Analyzers.dll", StringComparison.OrdinalIgnoreCase)))
                analyzers.Add(unityAnalyzers);
            var additional = (Reflect<string[]>(assembly.compilerOptions, "RoslynAdditionalFilePaths") ?? new string[0])
                .Where(a => !string.IsNullOrEmpty(a)).Select(Path.GetFullPath).Distinct().ToList();
            var analyzerConfig = Reflect<string>(assembly.compilerOptions, "AnalyzerConfigPath");
            if (analyzers.Count > 0 || additional.Count > 0 || !string.IsNullOrEmpty(analyzerConfig))
            {
                sb.Append("  <ItemGroup>").Append(k_NewLine);
                foreach (var a in analyzers)
                    sb.Append("    <Analyzer Include=\"").Append(Escape(a)).Append("\" />").Append(k_NewLine);
                foreach (var a in additional)
                    sb.Append("    <AdditionalFiles Include=\"").Append(Escape(a)).Append("\" />").Append(k_NewLine);
                if (!string.IsNullOrEmpty(analyzerConfig))
                    sb.Append("    <EditorConfigFiles Include=\"").Append(Escape(Path.GetFullPath(analyzerConfig))).Append("\" />").Append(k_NewLine);
                sb.Append("  </ItemGroup>").Append(k_NewLine);
            }

            // References: Unity/system DLLs + script assemblies we don't generate a project for
            var references = new List<string>();
            references.AddRange(assembly.compiledAssemblyReferences);
            references.AddRange(rsp.References);
            references.AddRange(dllSources);
            foreach (var r in assembly.assemblyReferences)
            {
                if (!generated.Contains(r.name))
                    references.Add(Path.IsPathRooted(r.outputPath) ? r.outputPath : Path.Combine(ProjectDirectory, r.outputPath));
            }

            sb.Append("  <ItemGroup>").Append(k_NewLine);
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var reference in references)
            {
                var full = Path.IsPathRooted(reference) ? reference : Path.Combine(ProjectDirectory, reference);
                var name = Path.GetFileNameWithoutExtension(full);
                if (!seen.Add(name))
                    continue;
                sb.Append("    <Reference Include=\"").Append(Escape(name)).Append("\">").Append(k_NewLine);
                sb.Append("      <HintPath>").Append(Escape(full)).Append("</HintPath>").Append(k_NewLine);
                sb.Append("      <Private>False</Private>").Append(k_NewLine);
                sb.Append("    </Reference>").Append(k_NewLine);
            }
            sb.Append("  </ItemGroup>").Append(k_NewLine);

            var projectRefs = assembly.assemblyReferences.Where(r => generated.Contains(r.name)).ToList();
            if (projectRefs.Count > 0)
            {
                sb.Append("  <ItemGroup>").Append(k_NewLine);
                foreach (var r in projectRefs)
                    sb.Append("    <ProjectReference Include=\"").Append(Escape(r.name)).Append(".csproj\" />").Append(k_NewLine);
                sb.Append("  </ItemGroup>").Append(k_NewLine);
            }

            sb.Append("  <Import Project=\"Sdk.targets\" Sdk=\"Microsoft.NET.Sdk\" />").Append(k_NewLine);
            sb.Append("  <ItemGroup>").Append(k_NewLine);
            foreach (var c in k_UnsupportedCapabilities)
                sb.Append("    <ProjectCapability Remove=\"").Append(c).Append("\" />").Append(k_NewLine);
            sb.Append("  </ItemGroup>").Append(k_NewLine);
            sb.Append("</Project>").Append(k_NewLine);
            return sb.ToString();
        }

        static string DefaultLangVersion
        {
            get
            {
#if UNITY_2021_2_OR_NEWER
                return "9.0";
#else
                return "8.0";
#endif
            }
        }

        static string RootNamespace(Assembly assembly)
        {
            var ns = Reflect<string>(assembly, "rootNamespace");
            if (!string.IsNullOrEmpty(ns))
                return ns;
            return assembly.name.StartsWith("Assembly-CSharp", StringComparison.Ordinal) ? EditorSettings.projectGenerationRootNamespace : string.Empty;
        }

        // -------------------------------------------------------------------------------------- sln

        string SolutionText(List<Assembly> assemblies)
        {
            var sb = new StringBuilder();
            sb.Append(k_NewLine);
            sb.Append("Microsoft Visual Studio Solution File, Format Version 12.00").Append(k_NewLine);
            sb.Append("# Visual Studio Version 17").Append(k_NewLine);
            foreach (var a in assemblies)
            {
                sb.Append("Project(\"{").Append(k_CSharpProjectType).Append("}\") = \"").Append(a.name).Append("\", \"")
                    .Append(a.name).Append(".csproj\", \"{").Append(Guid(a.name)).Append("}\"").Append(k_NewLine);
                sb.Append("EndProject").Append(k_NewLine);
            }
            sb.Append("Global").Append(k_NewLine);
            sb.Append("\tGlobalSection(SolutionConfigurationPlatforms) = preSolution").Append(k_NewLine);
            sb.Append("\t\tDebug|Any CPU = Debug|Any CPU").Append(k_NewLine);
            sb.Append("\tEndGlobalSection").Append(k_NewLine);
            sb.Append("\tGlobalSection(ProjectConfigurationPlatforms) = postSolution").Append(k_NewLine);
            foreach (var a in assemblies)
            {
                var g = Guid(a.name);
                sb.Append("\t\t{").Append(g).Append("}.Debug|Any CPU.ActiveCfg = Debug|Any CPU").Append(k_NewLine);
                sb.Append("\t\t{").Append(g).Append("}.Debug|Any CPU.Build.0 = Debug|Any CPU").Append(k_NewLine);
            }
            sb.Append("\tEndGlobalSection").Append(k_NewLine);
            sb.Append("\tGlobalSection(SolutionProperties) = preSolution").Append(k_NewLine);
            sb.Append("\t\tHideSolutionNode = FALSE").Append(k_NewLine);
            sb.Append("\tEndGlobalSection").Append(k_NewLine);
            sb.Append("EndGlobal").Append(k_NewLine);
            return sb.ToString();
        }

        static string Guid(string name)
        {
            using (var md5 = MD5.Create())
            {
                var hash = md5.ComputeHash(Encoding.UTF8.GetBytes("papyrus:" + name));
                return new Guid(hash).ToString().ToUpperInvariant();
            }
        }

        // -------------------------------------------------------------------------------------- utils

        static string Xml(string s)
        {
            return string.IsNullOrEmpty(s) ? string.Empty : SecurityElement.Escape(s);
        }

        // MSBuild item paths: escape % and ; as well as XML
        static string Escape(string s)
        {
            if (string.IsNullOrEmpty(s))
                return string.Empty;
            return SecurityElement.Escape(s.Replace("%", "%25").Replace(";", "%3B"));
        }

        static void WriteIfChanged(string path, string contents)
        {
            try
            {
                if (File.Exists(path) && File.ReadAllText(path) == contents)
                    return;
                File.WriteAllText(path, contents, new UTF8Encoding(false));
            }
            catch (Exception e)
            {
                Debug.LogWarning("[PAPyrus] " + path + " 쓰기 실패: " + e.Message);
            }
        }

        internal static T Reflect<T>(object target, string member) where T : class
        {
            if (target == null)
                return null;
            var t = target.GetType();
            var p = t.GetProperty(member, BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
            if (p != null)
                return p.GetValue(target, null) as T;
            var f = t.GetField(member, BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
            return f != null ? f.GetValue(target) as T : null;
        }
    }

    /// <summary>Minimal csc.rsp parser (defines, references, unsafe, nullable, langversion, analyzers).</summary>
    internal class ResponseFileData
    {
        public readonly List<string> Defines = new List<string>();
        public readonly List<string> References = new List<string>();
        public readonly List<string> Analyzers = new List<string>();
        public bool Unsafe;
        public string Nullable;
        public string LangVersion;

        public static ResponseFileData Parse(Assembly assembly, string projectDirectory)
        {
            var data = new ResponseFileData();
            var files = ProjectGeneration.Reflect<string[]>(assembly.compilerOptions, "ResponseFiles");
            IEnumerable<string> paths = files != null && files.Length > 0
                ? files
                : new[] { Path.Combine("Assets", "csc.rsp") };
            foreach (var f in paths)
            {
                var full = Path.IsPathRooted(f) ? f : Path.Combine(projectDirectory, f);
                if (!File.Exists(full))
                    continue;
                foreach (var raw in File.ReadAllLines(full))
                {
                    foreach (var token in Tokenize(raw))
                        data.Apply(token, projectDirectory);
                }
            }

            return data;
        }

        static IEnumerable<string> Tokenize(string line)
        {
            var sb = new StringBuilder();
            var quoted = false;
            foreach (var c in line)
            {
                if (c == '"')
                {
                    quoted = !quoted;
                    continue;
                }

                if (char.IsWhiteSpace(c) && !quoted)
                {
                    if (sb.Length > 0)
                    {
                        yield return sb.ToString();
                        sb.Length = 0;
                    }
                    continue;
                }

                sb.Append(c);
            }

            if (sb.Length > 0)
                yield return sb.ToString();
        }

        void Apply(string token, string projectDirectory)
        {
            if (token.Length < 2 || (token[0] != '-' && token[0] != '/'))
                return;
            var body = token.Substring(1);
            var colon = body.IndexOf(':');
            var key = (colon >= 0 ? body.Substring(0, colon) : body).ToLowerInvariant();
            var value = colon >= 0 ? body.Substring(colon + 1) : string.Empty;
            switch (key)
            {
                case "d":
                case "define":
                    Defines.AddRange(value.Split(new[] { ';', ',' }, StringSplitOptions.RemoveEmptyEntries));
                    break;
                case "r":
                case "reference":
                    foreach (var r in value.Split(new[] { ';', ',' }, StringSplitOptions.RemoveEmptyEntries))
                        References.Add(Path.IsPathRooted(r) ? r : Path.Combine(projectDirectory, r));
                    break;
                case "a":
                case "analyzer":
                    foreach (var r in value.Split(new[] { ';', ',' }, StringSplitOptions.RemoveEmptyEntries))
                        Analyzers.Add(Path.IsPathRooted(r) ? r : Path.Combine(projectDirectory, r));
                    break;
                case "unsafe":
                case "unsafe+":
                    Unsafe = true;
                    break;
                case "nullable":
                case "nullable+":
                    Nullable = string.IsNullOrEmpty(value) ? "enable" : value;
                    break;
                case "langversion":
                    LangVersion = value;
                    break;
            }
        }
    }
